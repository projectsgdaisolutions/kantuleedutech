// Unified helper to retrieve details by ID (with fuzzy matching/mapping for prefixed IDs)
// ============================================================
// UNIFIED COLLEGE DETAIL LOOKUP
// ============================================================

export function getCollegeDetailById(id) {
  if (!id) return null;

  const rawId = String(id)
    .trim()
    .toLowerCase();

  // ==========================================================
  // ID ALIASES
  //
  // These allow different IDs used by the university cards
  // and detail database to point to the same university.
  // ==========================================================

  const aliases = {
    // Philippines
    "up-manila": "ust-manila",
    "ust-manila": "ust-manila",
    "ust-philippines": "ust-manila",

    // Nepal
    "tribhuvan-iom": "tribhuvan-iom",
    "mcoms": "mcoms-nepal",

    // Kyrgyzstan
    "kyrgyzstan-ihsm": "ihsm",
    "kyrgyzstan-osh-state-university":
      "osh-state-university",
    "kyrgyzstan-asian-medical-institute":
      "asian-medical-institute",
  };

  // ==========================================================
  // REMOVE COUNTRY PREFIX
  // ==========================================================

  const withoutCountryPrefix = rawId
    .replace(/^india-/, "")
    .replace(/^russia-/, "")
    .replace(/^kyrgyzstan-/, "")
    .replace(/^kazakhstan-/, "")
    .replace(/^georgia-/, "")
    .replace(/^vietnam-/, "")
    .replace(/^nepal-/, "")
    .replace(/^philippines-/, "")
    .replace(/^usa-/, "");

  // ==========================================================
  // POSSIBLE IDs TO SEARCH
  // ==========================================================

  const possibleIds = [
    rawId,
    withoutCountryPrefix,
    aliases[rawId],
    aliases[withoutCountryPrefix],
  ].filter(Boolean);

  // Remove duplicates
  const uniqueIds = [
    ...new Set(possibleIds),
  ];

  // ==========================================================
  // SEARCH ALL COUNTRIES
  // ==========================================================

  for (const country in countryCollegesMap) {
    const colleges =
      countryCollegesMap[country] || [];

    const found = colleges.find(
      (college) =>
        uniqueIds.includes(
          String(college.id)
            .trim()
            .toLowerCase()
        )
    );

    if (found) {
      return found;
    }
  }

  // ==========================================================
  // SPECIAL FALLBACK
  //
  // If homepage uses "up-manila", but database has
  // "ust-philippines", find it directly.
  // ==========================================================

  if (rawId === "up-manila") {
    const philippines =
      countryCollegesMap.philippines || [];

    return (
      philippines.find(
        (college) =>
          college.id === "ust-manila" ||
          college.id === "ust-philippines"
      ) || null
    );
  }

  return null;
}